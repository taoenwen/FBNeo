// Look up a symbolic ROM-type token; returns true and sets *pOut when found.
extern "C" bool RomDataLookupMacro(const char* pszName, UINT32* pOut)
{
	if (!pszName || !pOut) return false;
	for (UINT32 i = 0; i < (sizeof(RDMacroTable) / sizeof(RDMacroTable[0])); i++) {
		if (0 == strcmp(pszName, RDMacroTable[i].pszName)) {
			*pOut = RDMacroTable[i].nValue;
			return true;
		}
	}
	return false;
}

